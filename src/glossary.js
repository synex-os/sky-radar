// Текст → HTML, где первое упоминание каждого термина — кнопка в словарик
function linkTerms(text) {
  const esc = s => s.replace(/[&<>"]/g, c => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;' }[c]));
  const hits = [];
  for (const [key, g] of Object.entries(GLOSSARY)) {
    const re = new RegExp(`(?<![\\p{L}])(?:${g.match.source})`, g.match.flags.includes('u') ? g.match.flags : g.match.flags + 'u');
    const m = re.exec(text);
    if (m) hits.push({ start: m.index, end: m.index + m[0].length, key });
  }
  hits.sort((a, b) => a.start - b.start);
  let out = '', pos = 0;
  for (const h of hits) {
    if (h.start < pos) continue;                      // термины не вкладываются друг в друга
    out += esc(text.slice(pos, h.start)) + `<button class="term" data-term="${h.key}">${esc(text.slice(h.start, h.end))}</button>`;
    pos = h.end;
  }
  return out + esc(text.slice(pos));
}
